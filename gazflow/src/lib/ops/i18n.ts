const DICTS: Record<Lang, Record<DictKey, string>> = { he, ar };

export function makeT(lang: Lang) {
  const dict = DICTS[lang];
  return (key: DictKey, vars?: Record<string, string | number>) =>
    Object.entries(vars ?? {}).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, String(v)), dict[key]);
}

export type T = ReturnType<typeof makeT>;

export function shekel(n: number, lang: Lang): string {
  // Western digits in both languages — what customers in Israel read on prices.
  void lang;
  return `₪${n.toLocaleString("en-US", { maximumFractionDigits: 0 })}`;
}
